import os

# Limit BLAS / parallel library thread counts (memory and speed control)
os.environ["OPENBLAS_NUM_THREADS"] = "8"
os.environ["MKL_NUM_THREADS"] = "8"
os.environ["OMP_NUM_THREADS"] = "8"
os.environ["NUMBA_NUM_THREADS"] = "8"
os.environ["VECLIB_MAXIMUM_THREADS"] = "8"
os.environ["NUMEXPR_NUM_THREADS"] = "8"

## Configuration ##
# Set the base directory for input/output data below.
# proj_dir must point to the directory containing "output/" and "Analysis/"
BASE_DIR = os.environ.get("PROJ_DIR", "path/to/your/project")  # <-- MODIFY THIS

# Metacell AnnData generated by Stage 7 (01_metacell_construct.py)
METACELL_H5AD = os.path.join(BASE_DIR, "Analysis", "metacell",
                             "human_all_celltypes_metacell_raw_k100.h5ad")

# Sample metadata (stage annotations per sample)
META_CSV = os.path.join(BASE_DIR, "Annotation_hvg5000", "final",
                        "hs_all_metadata_final.csv")

# Output directory for hormone analysis results
HORMONE_DIR = os.path.join(BASE_DIR, "Analysis", "hormone")

import numpy as np
import pandas as pd
import scanpy as sc
from scipy.stats import pearsonr, spearmanr

import hormone2cell

os.makedirs(HORMONE_DIR, exist_ok=True)

# ===========================================================================
# Part 1: Load metacell data and prepare sample metadata
# ===========================================================================
adata = sc.read_h5ad(METACELL_H5AD)
meta = pd.read_csv(META_CSV)

# Derive dataset id from the sample name
adata.obs["dataset"] = (
    adata.obs["sample_new"]
    .astype(str)
    .str.split("_")
    .str[0]
)

# All metacells come from single-cell data in this analysis
adata.obs["suspension_type"] = "sc"
adata.obs["cell_type"] = adata.obs["type_2"]
adata.obs['Tissue'] = 'Brain'

# Normalize sample naming (single-nucleus datasets map to their own id)
meta["sample_new"] = meta["sample"].astype(str)
for ds in ["hs09", "hs11", "hs12", "hs14"]:
    idx = meta["dataset"] == ds
    meta.loc[idx, "sample_new"] = ds

# Keep one stage annotation per sample, dropping ambiguous samples
sample_info = meta[["sample_new", "stage"]].drop_duplicates()
dup_samples = sample_info.groupby("sample_new")["stage"].nunique()
dup_samples = dup_samples[dup_samples > 1].index
sample_info = sample_info.loc[~sample_info["sample_new"].isin(dup_samples)].copy()
sample_info = sample_info.set_index("sample_new")

adata.obs["stage"] = adata.obs["sample_new"].map(sample_info["stage"])

adata.write_h5ad(os.path.join(HORMONE_DIR, "human_metacell_hormone.h5ad"))


# ===========================================================================
# Part 2: Per-stage hormone producing / receiving strength
# ===========================================================================
HORMONE_COLS = [
    "Hormone", "Celltype_tissue", "Strength", "Tissue",
    "hormone_display", "hormone_short", "Tier", "assay",
]

STAGES = sorted(adata.obs["stage"].dropna().unique())
BY_STAGE_DIR = os.path.join(HORMONE_DIR, "by_stage")
os.makedirs(BY_STAGE_DIR, exist_ok=True)

for stage in STAGES:
    print("=" * 80)
    print(stage)
    print("=" * 80)

    stage_id = f"S{stage.split('-')[0]}"
    stage_dir = os.path.join(BY_STAGE_DIR, stage_id)
    os.makedirs(stage_dir, exist_ok=True)

    # Subset to the current stage
    adata_stage = adata[adata.obs["stage"] == stage].copy()
    if adata_stage.n_obs < 50:
        print(f"Skip {stage}: fewer than 50 cells ({adata_stage.n_obs})")
        continue

    # Average expression per cell type within this stage
    ave_all_stage = hormone2cell.compute_aveExp_by_category(
        adata_stage,
        sc_sn_col="suspension_type",
        celltype_col="cell_type",
        tissue_col="Tissue"
    )

    # --- Hormone producing (single-cell assay only) ---
    mask = ave_all_stage["suspension_type"] == "sc"
    if mask.sum() == 0:
        print("No sc data for stage:", stage)
        dt_cell = pd.DataFrame(columns=HORMONE_COLS)
    else:
        dt_cell = run_hormone_strength(
            ave_all_stage.loc[mask],
            HORMONE_DEF, assay="cell", adjustment=True,
            include_cols=HPC_INCLUDE, exclude_cols=HPC_EXCLUDE,
            max_expression_file=os.path.join(stage_dir, "max_expression_cell.csv"),
            specificity_threshold=0.8, coverage_threshold=0.5,
            thresh_included_initial=0.1, thresh_excluded_initial=0.15,
            thresh_included_adjusted=0.5, thresh_excluded_adjusted=0.15,
        )
    dt_cell.to_csv(os.path.join(stage_dir, "hormone_producing_strength.csv"),
                   index=False)

    # --- Hormone receiving (single-cell assay only) ---
    mask = ave_all_stage["suspension_type"] == "sc"
    if mask.sum() == 0:
        print("No sc data for stage:", stage)
        dt_cell = pd.DataFrame(columns=HORMONE_COLS)
    else:
        dt_cell = run_hormone_strength(
            ave_all_stage.loc[mask],
            RECEPTOR_DEF, assay="cell", adjustment=True,
            include_cols=RECEPTOR_GENES, exclude_cols=[],
            max_expression_file=os.path.join(stage_dir, "max_expression_cell_receptor.csv"),
            thresh_included_initial=0.1, thresh_excluded_initial=0.15,
        )
    dt_cell.to_csv(os.path.join(stage_dir, "hormone_receiving_strength.csv"),
                   index=False)

    print(f"Finished {stage} | producing={dt_cell.shape}")

# ===========================================================================
# Part 4: Producer-receiver correlation across stages
# ===========================================================================
STAGE_LIST = [f"S{i:02d}" for i in range(1, 16)]

producer_all, receiver_all = [], []
for stage in STAGE_LIST:
    prod_file = os.path.join(BY_STAGE_DIR, stage, "hormone_producing_strength.csv")
    recv_file = os.path.join(BY_STAGE_DIR, stage, "hormone_receiving_strength.csv")

    if os.path.exists(prod_file):
        df = pd.read_csv(prod_file)
        df["stage"] = stage
        producer_all.append(df)
    if os.path.exists(recv_file):
        df = pd.read_csv(recv_file)
        df["stage"] = stage
        receiver_all.append(df)

producer_all = pd.concat(producer_all, ignore_index=True)
receiver_all = pd.concat(receiver_all, ignore_index=True)

# Stage x hormone matrices
producer_mat = producer_all.pivot_table(
    index=["Hormone", "Celltype_tissue"],
    columns="stage",
    values="Strength",
    aggfunc="mean",
    fill_value=0
).reindex(columns=STAGE_LIST, fill_value=0)

receiver_mat = receiver_all.pivot_table(
    index=["Hormone", "Celltype_tissue"],
    columns="stage",
    values="Strength",
    aggfunc="mean",
    fill_value=0
).reindex(columns=STAGE_LIST, fill_value=0)

# Correlate producing vs receiving strength trajectories per hormone pair
results = []
common_hormones = sorted(
    set(producer_mat.index.get_level_values(0)).intersection(
        receiver_mat.index.get_level_values(0)
    )
)

for hormone in common_hormones:
    prod_sub = producer_mat.loc[hormone]
    recv_sub = receiver_mat.loc[hormone]

    if isinstance(prod_sub, pd.Series):
        prod_sub = prod_sub.to_frame().T
    if isinstance(recv_sub, pd.Series):
        recv_sub = recv_sub.to_frame().T

    for prod_cell in prod_sub.index:
        prod_vec = prod_sub.loc[prod_cell].values
        if np.sum(prod_vec > 0) < 6:  # require signal in >= 6 stages
            continue

        for recv_cell in recv_sub.index:
            recv_vec = recv_sub.loc[recv_cell].values
            if np.sum(recv_vec > 0) < 6:
                continue

            # Require >= 4 stages with signal in both cell types
            overlap = np.sum((prod_vec > 0) & (recv_vec > 0))
            if overlap < 4:
                continue

            r, p = pearsonr(prod_vec, recv_vec)
            rho, p_s = spearmanr(prod_vec, recv_vec)
            results.append([
                hormone, prod_cell, recv_cell, r, p, rho, p_s,
                np.sum(prod_vec > 0), np.sum(recv_vec > 0), overlap
            ])

corr_df = pd.DataFrame(
    results,
    columns=[
        "Hormone", "Producer", "Receiver",
        "PearsonR", "PearsonP", "SpearmanR", "SpearmanP",
        "ProducerStages", "ReceiverStages", "OverlapStages"
    ]
)
# Keep only the cell-type part of the composite Celltype_tissue labels
corr_df["Producer"] = corr_df["Producer"].astype(str).str.split("____").str[-1]
corr_df["Receiver"] = corr_df["Receiver"].astype(str).str.split("____").str[-1]

corr_df.to_csv(os.path.join(BY_STAGE_DIR, "Hormone_ProducerReceiver_Correlation.csv"),
               index=False)

# ===========================================================================
# Part 5: Stage-group (prenatal / postnatal / adult) strength aggregation
# ===========================================================================
sig_df = corr_df.query("SpearmanR > 0.9 and SpearmanP < 0.05").copy()

# Mean strength per (hormone, cell type, stage)
producer_lookup = producer_all.groupby(["Hormone", "Celltype_tissue", "stage"])["Strength"].mean()
receiver_lookup = receiver_all.groupby(["Hormone", "Celltype_tissue", "stage"])["Strength"].mean()


def full_celltype(part, table):
    """Recover the full Celltype_tissue label that ends with `part`."""
    return table[table["Celltype_tissue"].str.endswith(part)]["Celltype_tissue"].iloc[0]


# Mean producing-receiving strength per significant pair
color_values = []
for _, row in sig_df.iterrows():
    hormone = row["Hormone"]
    prod_full = full_celltype(row["Producer"], producer_all)
    recv_full = full_celltype(row["Receiver"], receiver_all)

    vals = []
    for stage in STAGE_LIST:
        p = producer_lookup.get((hormone, prod_full, stage), np.nan)
        r = receiver_lookup.get((hormone, recv_full, stage), np.nan)
        if pd.notna(p) and pd.notna(r):
            vals.append((p + r) / 2)
    color_values.append(np.mean(vals) if len(vals) > 0 else np.nan)

sig_df["MeanStrength"] = color_values

# Top pair per hormone
top_pair_df = (sig_df.sort_values("SpearmanR", ascending=False)
               .groupby("Hormone").head(1))
top_pair_df["Type"] = np.where(
    top_pair_df["Producer"] == top_pair_df["Receiver"],
    "Autocrine", "Paracrine"
)

hormone_order = (top_pair_df.sort_values(["Type", "SpearmanR"],
                                         ascending=[True, False])
                 ["Hormone"].tolist())
pair_order = (top_pair_df.set_index("Hormone").loc[hormone_order]
              ["Producer"] + " -> " + top_pair_df.set_index("Hormone").loc[hormone_order]["Receiver"])
pair_order = pd.unique(pair_order).tolist()

sig_df["Pair"] = sig_df["Producer"] + " -> " + sig_df["Receiver"]

# Strength heatmap table (data underlying the removed heatmap figure)
heatmap_df = sig_df.pivot_table(
    index="Pair",
    columns="Hormone",
    values="MeanStrength",
    aggfunc="max"
).reindex(index=pair_order, columns=hormone_order)
heatmap_df.to_csv(os.path.join(BY_STAGE_DIR, "Hormone_ProducerReceiver_heatmap_strength.csv"),
                  index=True)

# ---------------------------------------------------------------------------
# Per-stage-group aggregation: prenatal / postnatal / adult
# ---------------------------------------------------------------------------
stage_groups = {
    "Prenatal": [f"S{i:02d}" for i in range(1, 8)],
    "Postnatal": [f"S{i:02d}" for i in range(8, 13)],
    "Adult": [f"S{i:02d}" for i in range(13, 16)],
}
stage_to_group = {s: gi for gi, stages in enumerate(stage_groups.values()) for s in stages}
stage_group_labels = list(stage_groups.keys())

producer_all = producer_all.copy()
receiver_all = receiver_all.copy()
producer_all["Group"] = producer_all["stage"].map(stage_to_group)
receiver_all["Group"] = receiver_all["stage"].map(stage_to_group)
producer_all = producer_all.dropna(subset=["Group"])
receiver_all = receiver_all.dropna(subset=["Group"])
producer_all["Group"] = producer_all["Group"].astype(int)
receiver_all["Group"] = receiver_all["Group"].astype(int)

prod_group_lookup = (producer_all
                     .groupby(["Hormone", "Celltype_tissue", "Group"])["Strength"].mean())
recv_group_lookup = (receiver_all
                     .groupby(["Hormone", "Celltype_tissue", "Group"])["Strength"].mean())

# Per-stage-group mean strength for each (Pair, Hormone) in sig_df
cell_data = {}
for _, row in sig_df.iterrows():
    hormone = row["Hormone"]
    prod_full = full_celltype(row["Producer"], producer_all)
    recv_full = full_celltype(row["Receiver"], receiver_all)
    pair_label = f"{row['Producer']} -> {row['Receiver']}"

    stage_vals = []
    for gi in range(len(stage_group_labels)):
        p = prod_group_lookup.get((hormone, prod_full, gi), np.nan)
        r = recv_group_lookup.get((hormone, recv_full, gi), np.nan)
        stage_vals.append((p + r) / 2 if pd.notna(p) and pd.notna(r) else np.nan)
    cell_data[(pair_label, hormone)] = stage_vals

# Export per-stage-group strength table
grouped_records = []
for (pair, hormone), stage_vals in cell_data.items():
    for gi, group_name in enumerate(stage_group_labels):
        grouped_records.append({
            "Pair": pair,
            "StageGroup": group_name,
            "Hormone": hormone,
            "MeanStrength": stage_vals[gi],
        })
grouped_df = pd.DataFrame(grouped_records)
heatmap_grouped = grouped_df.pivot_table(
    index=["Pair", "StageGroup"],
    columns="Hormone",
    values="MeanStrength",
    aggfunc="max",
)
heatmap_grouped.to_csv(
    os.path.join(BY_STAGE_DIR, "Hormone_ProducerReceiver_heatmap_stageSplit_strength.csv"),
    index=True,
)
